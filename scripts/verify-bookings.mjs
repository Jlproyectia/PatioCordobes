import assert from 'node:assert/strict';
import { handleBookings } from '../server/bookings.mjs';
import { openDatabase } from '../server/local-db.mjs';
const DB = openDatabase(':memory:');
const sent=[];
let fail=false;
const env={DB,RESEND_API_KEY:'test-secret',RESEND_FROM:'test@example.com',BOOKING_OWNER_EMAIL:'owner@example.com',BOOKING_BASE_URL:'https://patio.example',fetch:async(url,options)=>{if(fail)return new Response('{}',{status:503});sent.push(JSON.parse(options.body));return Response.json({id:'test'});}};
const data={name:'Prueba <segura>',email:'customer@example.com',date:new Date(Date.now()+86400000).toISOString().slice(0,10),guests:4,service:'cena',language:'es',requestId:crypto.randomUUID()};
const submit=(value,origin=env.BOOKING_BASE_URL)=>handleBookings(new Request(env.BOOKING_BASE_URL+'/api/bookings',{method:'POST',headers:{origin,'Content-Type':'application/json'},body:JSON.stringify(value)}),env);
assert.equal((await submit({...data,guests:0})).status,400);
assert.equal((await submit({...data,date:'2026-02-31'})).status,400);
assert.equal((await submit(data,'https://attacker.example')).status,403);
assert.equal((await submit({...data,website:'bot'})).status,400);
assert.equal((await submit(data)).status,200);
assert.equal(sent.length,1);
assert.match(sent[0].html,/Prueba &lt;segura&gt;/);
assert.equal((await submit(data)).status,200);
assert.equal(sent.length,1);
const link=sent[0].text.match(/https:\/\/\S+$/)[0];
assert.equal((await handleBookings(new Request(link),env)).status,200);
assert.equal(sent.length,1,'GET must not confirm or send');
const confirm=()=>handleBookings(new Request(link,{method:'POST',headers:{origin:env.BOOKING_BASE_URL}}),env);
fail=true;assert.equal((await confirm()).status,502);
assert.equal((await DB.prepare('SELECT customer_sent FROM bookings WHERE id = ?').bind(data.requestId).first()).customer_sent,0);
fail=false;assert.equal((await confirm()).status,200);assert.equal(sent.length,2);
assert.equal(sent[1].to[0],data.email);
assert.match(sent[1].text,/confirmada/);
assert.equal((await confirm()).status,200);assert.equal(sent.length,2,'Repeat confirmation must not resend');
assert.equal((await handleBookings(new Request(env.BOOKING_BASE_URL+'/reservas/confirmar?token=bad'),env)).status,404);
const expired={...data,email:'expired@example.com',requestId:crypto.randomUUID()};
await submit(expired);
const expiredLink=sent.at(-1).text.match(/https:\/\/\S+$/)[0];
await DB.prepare('UPDATE bookings SET expires_at = 0 WHERE id = ?').bind(expired.requestId).run();
assert.equal((await handleBookings(new Request(expiredLink),env)).status,410);
DB.close();
console.log('Booking flow verified: validation, origin, email escaping, pending state, scanner-safe GET, retry after failure, confirmation, deduplication and expired tokens.');
